// Writes the ESM entry points as thin wrappers over the CommonJS build, so `import` and `require` share one module
// instance and `instanceof` works across them (authoring/typescript.md, "Errors").
"use strict";

const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const out = path.join(root, "dist", "esm");
fs.mkdirSync(out, { recursive: true });
const header = "// Copyright 2026 OLO Labs\n// SPDX-License-Identifier: Apache-2.0\n// Generated by scripts/esm.cjs.\n";

for (const entry of ["index", "internal", "build"]) {
  const cjs = path.join(root, "dist", "cjs", entry + ".js");
  if (!fs.existsSync(cjs)) continue;
  const names = Object.keys(require(cjs)).filter((n) => n !== "default" && n !== "__esModule").sort();
  const js =
    header +
    `import cjs from "../cjs/${entry}.js";\n` +
    (names.length ? `export const { ${names.join(", ")} } = cjs;\n` : "") +
    "export default cjs;\n";
  fs.writeFileSync(path.join(out, entry + ".mjs"), js);
  fs.writeFileSync(path.join(out, entry + ".d.mts"), header + `export * from "../cjs/${entry}.js";\n`);
}
