using System.Globalization;
using System.Linq;
using System.Text;
using OloLabs.ToolGate.Sdk.Analyzers.Model;

namespace OloLabs.ToolGate.Sdk.Analyzers;

/// <summary>The C# the generator adds to a tool package: the package class, the typed accessors and the entry point.</summary>
internal static class Emitter
{
    private const string Hosting = "global::OloLabs.ToolGate.Sdk.Hosting";
    private const string Sdk = "global::OloLabs.ToolGate.Sdk";
    private const string GeneratedCode = "[global::System.CodeDom.Compiler.GeneratedCode(\"OloLabs.ToolGate.Sdk.Analyzers\", \"1\")]";

    /// <summary>A C# string literal; non-ASCII is escaped so the source file's encoding never matters.</summary>
    public static string Literal(string value)
    {
        var s = new StringBuilder(value.Length + 2);
        s.Append('"');
        foreach (char c in value)
        {
            switch (c)
            {
                case '"': s.Append("\\\""); break;
                case '\\': s.Append("\\\\"); break;
                default:
                    if (c < 0x20 || c > 0x7e) s.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                    else s.Append(c);
                    break;
            }
        }
        s.Append('"');
        return s.ToString();
    }

    public static string Package(PackageModel model)
    {
        var s = new StringBuilder();
        s.AppendLine("// <auto-generated/>");
        s.AppendLine("#nullable enable");
        s.AppendLine("#pragma warning disable");
        s.AppendLine();
        s.AppendLine("[assembly: " + Hosting + ".GeneratedPackageAttribute(typeof(global::OloLabs.ToolGate.Generated.ToolGatePackage))]");
        s.AppendLine();
        s.AppendLine("namespace OloLabs.ToolGate.Generated");
        s.AppendLine("{");
        s.AppendLine("    /// <summary>The descriptors and handlers of this package. Generated by the ToolGate source generator.</summary>");
        s.AppendLine("    " + GeneratedCode);
        s.AppendLine("    internal sealed class ToolGatePackage : " + Hosting + ".GeneratedPackage");
        s.AppendLine("    {");
        s.AppendLine("        private static readonly " + Hosting + ".GeneratedTool[] tools =");
        s.AppendLine("        {");
        foreach (var tool in model.Tools.Values)
        {
            string handler = tool.Method.ContainingType.ToDisplayString(PackageBuilder.TypeFormat);
            string factory = tool.HasFactory ? "static () => new " + handler + "()" : "null";
            string args = string.Join(", ", tool.Bindings.Select(b => b.Name switch
            {
                "$context" => "a.Context",
                "$cancellation" => "a.Cancellation",
                _ => "a.Get<" + b.TypeName + ">(" + Literal(b.Name) + ")",
            }));
            string wrap = tool.Shape switch
            {
                ReturnShape.Task => "FromTask",
                ReturnShape.ValueTask => "FromValueTask",
                _ => "FromValue",
            };
            s.AppendLine("            new " + Hosting + ".GeneratedTool(");
            s.AppendLine("                " + Literal(tool.Name) + ",");
            s.AppendLine("                " + Literal(tool.Canonical) + ",");
            s.AppendLine("                typeof(" + handler + "),");
            s.AppendLine("                " + factory + ",");
            s.AppendLine("                static (h, a) => " + Hosting + ".HandlerResult." + wrap + "(((" + handler + ")h)." + Escape(tool.Method.Name) + "(" + args + "))),");
        }
        s.AppendLine("        };");
        s.AppendLine();
        s.AppendLine("        public override string IndexJson => " + Literal(model.IndexJson) + ";");
        s.AppendLine();
        s.AppendLine("        public override global::System.Collections.Generic.IReadOnlyList<" + Hosting + ".GeneratedTool> Tools => tools;");
        s.AppendLine("    }");
        s.AppendLine("}");
        return s.ToString();
    }

    private static string Escape(string identifier) =>
        Microsoft.CodeAnalysis.CSharp.SyntaxFacts.GetKeywordKind(identifier) != Microsoft.CodeAnalysis.CSharp.SyntaxKind.None ? "@" + identifier : identifier;

    public static string EntryPoint() =>
        "// <auto-generated/>\n" +
        "#nullable enable\n\n" +
        "namespace OloLabs.ToolGate.Generated\n" +
        "{\n" +
        "    /// <summary>Starts the ToolGate runtime (standalone or governed, from the environment).</summary>\n" +
        "    " + GeneratedCode + "\n" +
        "    internal static class ToolGateProgram\n" +
        "    {\n" +
        "        public static global::System.Threading.Tasks.Task<int> Main(string[] args) =>\n" +
        "            " + Hosting + ".ToolGateRuntime.RunAsync(args);\n" +
        "    }\n" +
        "}\n";

    public static string Accessors(AccessorClass a)
    {
        var s = new StringBuilder();
        s.AppendLine("// <auto-generated/>");
        s.AppendLine("#nullable enable");
        s.AppendLine();
        string indent = "";
        if (a.Namespace.Length > 0)
        {
            s.AppendLine("namespace " + a.Namespace);
            s.AppendLine("{");
            indent = "    ";
        }
        s.AppendLine(indent + "/// <summary>Typed access to the values the tools in " + Xml(a.HandlerClass) + " declare. Generated by the ToolGate source generator.</summary>");
        s.AppendLine(indent + GeneratedCode);
        s.AppendLine(indent + "public static class " + a.ClassName);
        s.AppendLine(indent + "{");
        bool first = true;
        foreach (var (accessor, contextMember, view, valuesType, what, values) in new[]
        {
            ("Global", "Global", "Globals", Sdk + ".IValues", "globals", a.Globals),
            ("Secret", "Secret", "Secrets", Sdk + ".IValues", "secrets", a.Secrets),
            ("Jwt", "JWT", "Claims", Sdk + ".IJwt", "JWT claims", a.Claims),
        })
        {
            if (values.Count == 0) continue;
            if (!first) s.AppendLine();
            first = false;
            string i = indent + "    ";
            s.AppendLine(i + "/// <summary>The " + what + " of this invocation.</summary>");
            s.AppendLine(i + "public static " + view + " " + accessor + "(" + Sdk + ".ToolContext context) => new " + view + "(context." + contextMember + ");");
            s.AppendLine();
            s.AppendLine(i + "/// <summary>Declared " + what + ", each read with the getter for its type.</summary>");
            s.AppendLine(i + "public sealed class " + view);
            s.AppendLine(i + "{");
            s.AppendLine(i + "    private readonly " + valuesType + " values;");
            s.AppendLine();
            s.AppendLine(i + "    internal " + view + "(" + valuesType + " values) { this.values = values; }");
            foreach (var v in values)
            {
                string member = PackageBuilder.Member(v.Key, view);
                string n = Literal(v.Key);
                s.AppendLine();
                s.AppendLine(i + "    /// <summary>" + Xml(v.Key) + " (" + v.Value + ").</summary>");
                s.AppendLine(i + "    " + v.Value switch
                {
                    "INT" => "public int " + member + " => values.GetIntValue(" + n + ");",
                    "LONG" => "public long " + member + " => values.GetLongValue(" + n + ");",
                    "NUMBER" => "public double " + member + " => values.GetNumberValue(" + n + ");",
                    "BOOLEAN" => "public bool " + member + " => values.GetBooleanValue(" + n + ");",
                    "DATE" => "public global::System.DateOnly " + member + " => values.GetDateValue(" + n + ");",
                    "DATE_TIME" => "public global::System.DateTimeOffset " + member + " => values.GetDateTimeValue(" + n + ");",
                    "DURATION" => "public global::System.TimeSpan " + member + " => values.GetDurationValue(" + n + ");",
                    "BINARY" => "public byte[] " + member + " => values.GetBinaryValue(" + n + ");",
                    "OBJECT" => "public T " + member + "<T>() => values.GetObjectValue<T>(" + n + ");",
                    "ARRAY" => "public global::System.Collections.Generic.IReadOnlyList<T> " + member + "<T>() => values.GetListValue<T>(" + n + ");",
                    _ => "public string " + member + " => values.GetStringValue(" + n + ");",
                });
            }
            s.AppendLine(i + "}");
        }
        s.AppendLine(indent + "}");
        if (a.Namespace.Length > 0) s.AppendLine("}");
        return s.ToString();
    }

    private static string Xml(string text) => text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
